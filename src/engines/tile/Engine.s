; Engine.s -- the ENGINE segment: the tile engine, behind silky-gs's interface (ImportEngine.s), in place of its PPU layer, PEA
; field, blitter and compilers.  The runtime in MAIN and the game know only that interface.
;
;   Front.s        the runtime's entry points, a render, the NES task's cell writes
;   OamScan.s      silky's OAM scan
;   (Sprite.s and SprLib.s, the sprites, are their own segments)
;   Scroll.s       the cells and their state layer (M11's)
;   Tiles.s        the tileset: its banks, the lazy compiler, attribute changes and invalidation (M11's)
;   ppu_regs.s, ppu_palette.s, rom_color.s    silky's own
;   generated by gen.js, in game/tile/: ClipCode.s, Walk.s, Tables.s


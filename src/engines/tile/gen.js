#!/usr/bin/env node
'use strict';

/**
 * gen.js -- generate the tile engine's sources (run by scripts/lib/nromBuild.js assembleGame, with the game's folder)
 *
 * ClipCode.s  TileFallback and the edges' ClipE<e>: from a slot's stub to the clip case.  SetVecs, the clip cases.
 * Walk.s      The runs along a line of cells: an edge's role into their words, or out.
 * Tables.s    RoleTab, CellRow, CellCol, FV, constants.
 * SprCode.s   ExposeBody, copied to every tile slot of the expose bank; the expose trampolines and clip cases.
 * SprData.s   The sprites' cell and screen tables.  SprEqu.s: their sizes.
 */

const fs = require('fs');
const path = require('path');
const { convertRomTile2 } = require('../../../scripts/lib/nesTileConvert.js');
const GAME = process.argv[2];           // The game the engine is generated for (assembleGame)
if (!GAME) throw new Error('usage: gen.js <game folder>');
// What only this engine wants to know about a game: its solid tile (a nametable byte), and any dynamic tiles' art
const tileGame = require(path.join(GAME, 'TileGame.js'));
const dynart = tileGame.dynart ? tileGame.dynart() : { tiles: [], frames: [[]] };
const solidTile = tileGame.solidTile;
if (!(solidTile >= 0 && solidTile < 256)) throw new Error('TileGame.js: no solidTile');
// Whether the engine checks the solid tile's CHR at run time (SolidCheck).  A game that knows its solid tile is always blank says
// solidCheck: false, and the engine takes its word for it: with CHR-RAM the game knows more than a check of the CHR can tell
const SOLID_CHECK = tileGame.solidCheck === false ? 0 : 1;
// What a frame that doesn't scroll draws: 'all' (every cell but the solid tile's: M14's) or 'changes' (only what changed: M13's)
const stillFrames = tileGame.stillFrames || 'all';
if (!['all', 'changes'].includes(stillFrames)) throw new Error(`TileGame.js: stillFrames is 'all' or 'changes'`);
const STILL_DIRTY = stillFrames === 'changes' ? 1 : 0;
if (STILL_DIRTY && tileGame.dynart) throw new Error("TileGame.js: dynamic tiles change with no write, so they need stillFrames: 'all'");
const OUT = path.join(__dirname, '..', '..', 'game', 'tile');   // Scratch, like the rest of game/
fs.mkdirSync(OUT, { recursive: true });
const BG_TABLE = 256;                   // A cell's slots are at $8000 up, whichever table PPUCTRL selects: that says what they hold
const hex4 = n => '$' + (n & 0xFFFF).toString(16).toUpperCase().padStart(4, '0');
function writer(file) {
    const out = ['; GENERATED by engines/tile/gen.js -- do not edit', '', '            mx    %00', ''];
    const emit = (label, op, operand = '', comment = '') =>
        out.push(`${label.padEnd(16)}${op.padEnd(6)}${operand.padEnd(24)}${comment ? ' ; ' + comment : ''}`.trimEnd());
    const save = () => fs.writeFileSync(path.join(OUT, file), out.join('\n') + '\n');
    return { out, emit, save };
}
const dws = (emit, words, per = 8) => { for (let i = 0; i < words.length; i += per) emit('', 'dw', words.slice(i, i + per).join(',')); };

// A slot (Tiles.s): +0 the body (at most 97 bytes), +97 three spare bytes, +100 the 8 clip entries, +124 the next slot's advance
const SOLIDTEST = 97;                   // The solid tile's spare bytes: the word of a cell that holds it, and a jmp to its body (below ROLE0: code compares)
const STRIDE = 128, ROLE0 = 100, ROLESTEP = 3;
const SOLIDWORD = (BG_TABLE + solidTile) * STRIDE;
const clipRole = e => e ? ROLE0 + (e - 1) * ROLESTEP : 0;
const scr = off => `$${(0x010000 + off).toString(16).toUpperCase()},x`;


const H = [
    [[0, false], [2, false]],
    [[1, false], [2, false]],
    [[2, false]],
    [[3, true]],
    [[0, false], [1, false]],
    [[0, false]],
    [[0, true]],
];
const ccLabel = (h, dir, row) => `CC${h}${dir}${row}`;
const clipEntry = (h, v) => (v < 8 ? ccLabel(h, 'D', v) : ccLabel(h, 'U', 14 - v));
{
    const { out, emit, save } = writer('ClipCode.s');
    // A = palette * $4000, Y = the screen address, the slot's return address on the stack.  Then: DBR = the colored bitmap bank
    // (the caller's pushed), Y = the tile's bitmap, X = the screen address.  The lsrs leave C clear, for the cell
    // A's low byte is the slot's bank (the stub's: Tiles.s).  In the thread (ThS not 0) the slot's jsr landed on the last two
    // bytes of the cell's list entry: ThFix takes what they held, for ClipDone (the return address: its high byte is the
    // entry's, or less 7 for the slot's +0; then the bank).  And a clip entry has no advance in front of it, so it is done here.
    // Nothing here pushes a word, so the entry's first byte stays
    const adv = (x, body) => {
        emit('', 'ldx', 'ThS');
        emit('', 'beq', x);
        emit('', 'sta', 'ThFix+2');
        emit('', 'lda', '1,s');
        if (body) { emit('', 'sec'); emit('', 'sbc', '#7'); }
        emit('', 'sta', 'ThFix');
        if (!body) { emit('', 'tya'); emit('', 'adc', 'Step'); emit('', 'tay'); }
        emit('', 'lda', 'ThFix+2');
    };
    const dbr = (zero) => {             // DBR, by a byte (ColorPtr's low byte is 0)
        emit('', 'phb');
        emit('', 'sep', '#$20');
        emit('', 'lda', zero ? 'ColorPtr' : 'ColorW');
        emit('', 'pha');
        emit('', 'plb');
        emit('', 'rep', '#$20');
    };
    const way = () => {
        emit('', 'tyx');
        emit('', 'and', '#$C000');
        emit('', 'sta', 'LzBase');
        emit('', 'pla');
        emit('', 'and', '#$FF80');
        emit('', 'lsr');
        emit('', 'lsr');
        emit('', 'ora', 'LzBase');
        emit('', 'tay');
        dbr(false);
    };
    out.push('TileFallback');
    adv('TileFallX', true);
    out.push('TileFallX');
    way();
    emit('', 'jmp', 'CC0D0');
    for (let e = 1; e < 9; e++) {
        out.push(`ClipE${e}`);
        adv(`ClipX${e}`);
        out.push(`ClipX${e}`);
        way();
        emit(`ClipT${e}`, 'jmp', 'CC0D0');
    }
    // A dynamic tile's clip entries: the same clip cases, reading its bytes on this frame's page, with DBR = 0
    for (let e = 1; e < 9; e++) {
        out.push(`DynE${e}`);
        adv(`DynX${e}`);
        out.push(`DynX${e}`);
        emit('', 'pla');
        emit('', 'and', '#$FF80');
        emit('', 'asl');
        emit('', 'xba');
        emit('', 'and', '#$00FF');
        emit('', 'asl');
        emit('', 'tax');
        emit('', 'ldal', 'DynOff,x');
        emit('', 'clc');
        emit('', 'adc', 'DynD');
        emit('', 'tyx');
        emit('', 'tay');
        dbr(true);
        emit(`DynT${e}`, 'jmp', 'CC0D0');
    }
    out.push('SetVecs');
    for (let e = 1; e < 9; e++) {
        if (e === 3) {                  // Without a fine vertical scroll, only the left and right edges are in use
            emit('', 'lda', 'SY');
            emit('', 'bne', ':rest');
            emit('', 'rts');
            out.push(':rest');
        }
        const h = e % 3, v = Math.floor(e / 3);
        emit('', 'lda', `HC+${2 * h}`);
        emit('', 'clc');
        emit('', 'adc', `VC+${2 * v}`);
        emit('', 'tax');
        emit('', 'lda', 'ClipTargetTab,x');
        emit('', 'sta', `ClipT${e}+1`);
        emit('', 'sta', `DynT${e}+1`);
    }
    emit('', 'rts');
    const targets = [];
    for (let i = 0; i < 7 * 32; i += 2) {
        const h = i >> 5, v = (i & 31) >> 1;
        if (v > 14) { targets.push('0'); continue; }
        if (H[h].some(s => s[1])) {
            emit(`CT${i}`, 'sep', '#$20');
            emit('', 'jmp', clipEntry(h, v));
            targets.push(`CT${i}`);
        } else targets.push(clipEntry(h, v));
    }
    out.push('ClipTargetTab');
    dws(emit, targets);
    for (let h = 0; h < 7; h++) {
        const byte = H[h].some(s => s[1]);
        for (const dir of ['D', 'U']) {
            const rows = dir === 'D' ? [0, 1, 2, 3, 4, 5, 6, 7] : [7, 6, 5, 4, 3, 2, 1, 0];
            for (const row of rows) {
                H[h].forEach(([off], k) => {
                    emit(k === 0 ? ccLabel(h, dir, row) : '', 'lda:', `${hex4(row * 4 + off)},y`);
                    emit('', 'stal', scr(row * 160 + off));
                });
            }
            if (byte) emit('', 'rep', '#$20');
            emit('', 'jmp', 'ClipDone');
        }
    }
    save();
}

// Walk.s: the runs along a line of cells, unrolled, one run per job and direction.  Along a column the cells are 1024
// bytes apart, up to 30 in a run; along a row 32, up to 32.  A table gives the entry for each length, and each cell's offset is in its instructions
{
    const { out, emit, save } = writer('Walk.s');
    const WORD = 4;
    const solidWord = SOLIDWORD, solidTest = solidWord + SOLIDTEST;
    const run = (name, stride, max, body) => {
        out.push(name);
        dws(emit, ['0', ...Array.from({ length: max }, (_, k) => `${name}${k + 1}`)]);
        for (let k = max - 1; k >= 0; k--) {
            out.push(`${name}${k + 1}`);
            body(k * stride);
        }
        emit('', 'plb');
        emit('', 'rts');
    };
    const lines = [['Col', 1024, 30], ['Row', 32, 32]];   // Along a column, or along a row
    // A = a cell's new list entry (its word - 1 with a role, its tile's advance - 1 without, a blank stub for the solid
    // tile): into both lists, at the addresses the cell holds (Lists.s).  The entry's bank byte is the cell's bank byte, which
    // a role does not change
    const CELL_LR = 8, CELL_LC = 10, FLAGS = 1;
    const entry = (off, label) => {
        emit(label || '', 'ldx:', `$${(off + CELL_LR).toString(16)},y`);
        emit('', 'stal', '$000000,x');
        emit('', 'ldx:', `$${(off + CELL_LC).toString(16)},y`);
        emit('', 'stal', '$000000,x');
    };
    // Y = the first cell.  The word keeps its tile and takes role WVal
    const role = off => {
        emit('', 'lda:', `$${(off + WORD).toString(16)},y`);
        emit('', 'and', '#$FF80');
        emit('', 'ora', 'WVal');
        emit('', 'sta:', `$${(off + WORD).toString(16)},y`);
        emit('', 'dec');
        entry(off);
    };
    // The same, with no role: the solid tile's word is SOLIDTEST, and its entry the blank stub for its flags (as ListSync)
    const clear = off => {
        emit('', 'lda:', `$${(off + WORD).toString(16)},y`);
        emit('', 'and', '#$FF80');
        if (solidWord) {
            emit('', 'cmp', `#${solidWord}`);
            emit('', 'beq', ':s');
        }
        emit('', 'sta:', `$${(off + WORD).toString(16)},y`);
        emit('', 'sec');
        emit('', 'sbc', '#5');
        if (solidWord) {
            emit('', 'bra', ':e');
            emit(':s', 'lda', `#${solidTest}`);
            emit('', 'sta:', `$${(off + WORD).toString(16)},y`);
            emit('', 'lda:', `$${(off + FLAGS).toString(16)},y`);
            emit('', 'and', '#$1111');          // L, R, U, D are bits 0, 4, 8, 12
            emit('', 'pha');
            emit('', 'xba');
            emit('', 'asl');
            emit('', 'asl');
            emit('', 'ora', '1,s');
            emit('', 'and', '#$00FF');
            emit('', 'asl');
            emit('', 'asl');
            emit('', 'asl');
            emit('', 'clc');
            emit('', 'adc', '#BLANK-1');
            emit('', 'plx');
        }
        entry(off, solidWord ? ':e' : '');
    };
    for (const [line, stride, max] of lines) {
        run(`Role${line}`, stride, max, role);
        run(`Clear${line}`, stride, max, clear);
    }
    save();
}

// The sprite bank: exposes take Y = the screen address, DBR = $01
{
    const { out, emit, save } = writer('SprCode.s');
    out.push('ExposeBody      ; copied to every tile slot of the expose bank');
    for (let row = 0; row < 8; row++) for (const off of [0, 2]) {
        emit('', 'lda:', `${hex4(row * 160 + off)},y`);
        emit('', 'sta:', `${hex4(row * 160 + off)},y`);
    }
    emit('', 'rtl');
    emit('', 'db', '0');
    for (let e = 1; e < 9; e++) {       // (in the thread, the advance first: as ClipCode.s)
        emit(`ExposeE${e}`, 'lda', 'ThS');
        emit('', 'beq', `ExposeT${e}`);
        emit('', 'tya');
        emit('', 'adc', 'Step');
        emit('', 'tay');
        emit(`ExposeT${e}`, 'jmp', 'EC0D0');
    }
    out.push('EVec');
    dws(emit, Array.from({ length: 8 }, (_, i) => `ExposeE${i + 1}`));
    out.push('SetEVecs        ENT');
    emit('', 'phb');
    emit('', 'phk');
    emit('', 'plb');
    for (let e = 1; e < 9; e++) {
        if (e === 3) {
            emit('', 'lda', 'SY');
            emit('', 'beq', ':done');
        }
        const h = e % 3, v = Math.floor(e / 3);
        emit('', 'lda', `HC+${2 * h}`);
        emit('', 'clc');
        emit('', 'adc', `VC+${2 * v}`);
        emit('', 'tax');
        emit('', 'lda', 'ETargetTab,x');
        emit('', 'sta', `ExposeT${e}+1`);
    }
    out.push(':done');
    emit('', 'plb');
    emit('', 'rtl');
    const eEntry = (h, v) => 'EC' + clipEntry(h, v).slice(2);
    const targets = [];
    for (let i = 0; i < 7 * 32; i += 2) {
        const h = i >> 5, v = (i & 31) >> 1;
        if (v > 14) { targets.push('0'); continue; }
        if (H[h].some(s => s[1])) {
            emit(`ECT${i}`, 'sep', '#$20');
            emit('', 'jmp', eEntry(h, v));
            targets.push(`ECT${i}`);
        } else targets.push(eEntry(h, v));
    }
    out.push('ETargetTab');
    dws(emit, targets);
    for (let h = 0; h < 7; h++) {
        const byte = H[h].some(s => s[1]);
        for (const dir of ['D', 'U']) {
            const rows = dir === 'D' ? [0, 1, 2, 3, 4, 5, 6, 7] : [7, 6, 5, 4, 3, 2, 1, 0];
            for (const row of rows) {
                H[h].forEach(([off], k) => {
                    emit(k === 0 ? 'EC' + ccLabel(h, dir, row).slice(2) : '', 'lda:', `${hex4(row * 160 + off)},y`);
                    emit('', 'sta:', `${hex4(row * 160 + off)},y`);
                });
            }
            if (byte) emit('', 'rep', '#$20');
            emit('', 'rtl');
        }
    }
    save();
}
// The sprites' tables.  Indexed by the world position * 2 (+ 16: the next cell): each wraps, so a sprite needs no origin or modulo
{
    const { out, emit, save } = writer('SprData.s');
    const tab = (name, words, per = 16) => { out.push(name); dws(emit, words.map(String), per); };
    // A cell's row and column for a world line and pixel, for each mirroring: SprMirrorL copies one pair to WRow and WCol
    const ROWS = 200 + 480 + 40, COLS = 256 + 512 + 40;
    const cellRow = r => (r % 30) * 1024 + (r >= 30 ? 0x8000 : 0);
    tab('WRowV', Array.from({ length: ROWS }, (_, v) => hex4(cellRow((v >> 3) % 30))));
    tab('WRowH', Array.from({ length: ROWS }, (_, v) => hex4(cellRow((v >> 3) % 60))));
    tab('WColV', Array.from({ length: COLS }, (_, h) => { const c = (h >> 3) & 63; return hex4((c & 31) * 32 + (c >> 5) * 0x8000); }));
    tab('WColH', Array.from({ length: COLS }, (_, h) => hex4(((h >> 3) & 31) * 32)));
    out.push(`WROWS           equ   ${ROWS}`);
    out.push(`WCOLS           equ   ${COLS}`);
    out.push(`WRow            ds    ${ROWS * 2}`);
    out.push(`WCol            ds    ${COLS * 2}`);
    tab('Sub160', Array.from({ length: 8 }, (_, i) => i * 160));
    tab('SprY', Array.from({ length: 200 }, (_, y) => 0x2000 + 16 + y * 160));
    tab('WRow2', Array.from({ length: 30 }, (_, r) => hex4(r * 1024)));
    tab('WCol2', Array.from({ length: 64 }, (_, c) => hex4((c & 31) * 32 + (c >> 5) * 0x8000)));
    tab('Band1280', Array.from({ length: 8 }, (_, r) => r * 1280));
    save();
}
{
    const { out, save } = writer('SprEqu.s');
    out.push('LISTSWAP        equ   $1004');    // 410 entries of 10 bytes (a whole number: SprExposeN runs the list): 64 8x16 sprites touch at most 384 cells
    out.push('LISTBSWAP       equ   $A00');     // 256 entries: 5 rows of 32 at most
    out.push('LISTENTRY       equ   10');
    out.push('BODYBYTES       equ   98');
    out.push(`SOLIDWORD       equ   ${SOLIDWORD}`);
    out.push(`SOLIDTEST       equ   ${SOLIDWORD + SOLIDTEST}`);
    out.push(`ROLE0           equ   ${ROLE0}`);
    out.push('SLOT_ADV        equ   124');
    out.push('ESTUB           equ   $40');
    out.push('BLANK           equ   $0100');
    out.push('BLANK_N         equ   86');
    out.push('SPR_COMP_TBL    equ   $7000');
    out.push('SPR16_KEY       equ   $2000');
    out.push(`TILE_STILL_DIRTY equ   ${STILL_DIRTY}`);
    save();
}

{
    const { out, emit, save } = writer('Tables.s');
    out.push(`TILE_STILL_DIRTY equ   ${STILL_DIRTY}`);
    out.push(`SOLIDTILE       equ   ${solidTile}`);
    out.push(`SOLID_CHECK     equ   ${SOLID_CHECK}`);
    out.push(`SOLIDWORD       equ   ${SOLIDWORD}`);
    out.push(`SOLIDTEST       equ   ${SOLIDWORD + SOLIDTEST}`);
    out.push(`BGWORD          equ   ${BG_TABLE * STRIDE}`);
    out.push('BLANK           equ   $0100');
    out.push('BLANK_N         equ   86');
    out.push('SLOT_ADV        equ   124');
    out.push(`ROLE0           equ   ${ROLE0}`);
    // The dynamic tiles.  Each one's code, copied to its slot by DynInstall: never run from here
    const DYN_TILES = 8, DYN_PAGES = dynart.frames.length, DYN_ART = dynart.tiles.length;
    out.push(`DYN_TILES       equ   ${DYN_TILES}`);
    out.push(`DYN_PAGES       equ   ${DYN_PAGES}`);
    out.push(`DYN_ART         equ   ${DYN_ART}`);
    out.push('DYN_PAL         equ   3');
    for (let id = 0; id < DYN_TILES; id++) {
        out.push(`DynBody${id}`);
        emit('', 'lda', 'DynD');
        emit('', 'tcd');
        for (let w = 0; w < 16; w++) {
            emit('', 'lda', `${id * 32 + w * 2}`);
            emit('', 'sta:', `${(w >> 1) * 160 + (w & 1) * 2},y`);
        }
        emit(id ? '' : 'DynPage', 'lda', '#$0000', id ? '' : "The engine's page (DynInstall)");
        emit('', 'tcd');
        emit('', 'rtl');
    }
    out.push('DYN_BODY        equ   DynBody1-DynBody0');
    out.push('DYN_PAGEOP      equ   DynPage+1-DynBody0');
    emit('', 'err', 'DYN_BODY/98', 'Too big for its slot');
    out.push('DynBodyT');
    dws(emit, Array.from({ length: DYN_TILES }, (_, id) => `DynBody${id}`));
    out.push('DynTiles        ; Per id: its tile (a nametable byte), or $FFFF');
    dws(emit, Array.from({ length: DYN_TILES }, (_, id) => id < DYN_ART ? hex4(dynart.tiles[id]) : '$FFFF'));
    out.push('DynOff          ; Per tile: its id * 32');
    dws(emit, Array.from({ length: 256 }, (_, t) => Math.max(0, dynart.tiles.indexOf(t)) * 32), 16);
    out.push('DynBits         ; The 2-bit tiles of the art: page, then id');
    for (const f of dynart.frames) for (const t of f) dws(emit, Array.from(convertRomTile2(t, 0)).slice(0, 32).reduce((a, v, i) => { if (i & 1) a[a.length - 1] |= v << 8; else a.push(v); return a; }, []).map(hex4));
    out.push('RoleTab');
    dws(emit, Array.from({ length: 9 }, (_, e) => hex4(clipRole(e))), 9);
    out.push('CellRow         ; per row: its offset in the cell bank');
    dws(emit, Array.from({ length: 60 }, (_, r) => hex4((r % 30) * 1024 + (r >= 30 ? 0x8000 : 0))));
    out.push('CellCol         ; per map column: nametable and column');
    dws(emit, Array.from({ length: 64 }, (_, c) => hex4((c & 31) * 32 + (c >> 5) * 0x8000)));
    out.push('Line160         ; sy * 2: sy * 160');
    dws(emit, Array.from({ length: 9 }, (_, i) => String(i * 160)), 9);
    // FV: per frame type, Span, the first tile's Y - X0, NextStep, NextStepW, the first strip
    const SEAM = 0x8000 - 31 * 32;
    out.push('FV');
    for (let o = 0; o < 4; o++) {
        for (const a of [0, 1]) {
            for (const b of [0, 1]) {
                const NC = 32 + a, NR = 25 + b;
                const v = [
                    [1280 - 4 * NC, 0, 1024, -29 * 1024, 0],
                    [-1280 - 4 * NC, (NR - 1) * 1280, -1024, 29 * 1024, NR - 1],
                    [4 - 1280 * NR, 0, 32, SEAM, 0],
                    [-4 - 1280 * NR, 4 * (NC - 1), -32, -SEAM, NC - 1],
                ][o];
                emit('', 'dw', [...v, 0, 0, 0].map(hex4).join(','));
            }
        }
    }
    save();
}
